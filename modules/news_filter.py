# 카테고리 분류
# ══════════════════════════════════════════════════════════════════════════════

def classify(title: str) -> str:
    """
    뉴스 카테고리 분류.

    순서:
        0. 부동산 여부 확인
        1. 청약
        2. 재건축
        3. 세제
        4. 정책
        5. 공급개발
        6. 부산경남
        7. 시장동향

    부동산 관련성이 없는 기사는
    '제외'를 반환한다.

    news_pipeline.py의 기존 구조에서
    '제외'는 results에 존재하지 않는 카테고리이므로
    자동으로 HTML 저장 대상에서 빠진다.
    """

    if not title:
        return "제외"

    # ----------------------------------------------------------
    # 가장 중요한 1차 부동산 필터
    # ----------------------------------------------------------

    if not is_estate_related(
        title
    ):

        return "제외"

    # ----------------------------------------------------------
    # 정규화
    # ----------------------------------------------------------

    t = normalize(
        title
    )

    if not t:
        return "제외"

    # ----------------------------------------------------------
    # 청약
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "청약",
            "무순위",
            "청약통장",
            "특별공급",
            "일반공급",
            "분양권",
            "전매제한",
            "청약홈",
        ]
    ):

        return "청약"

    # ----------------------------------------------------------
    # 재건축 / 재개발
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "재건축",
            "재개발",
            "정비사업",
            "정비구역",
            "가로주택",
            "소규모재건축",
            "리모델링",
            "추진위원회",
            "조합",
            "시공사",
            "관리처분",
            "이주비",
        ]
    ):

        return "재건축"

    # ----------------------------------------------------------
    # 세제
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "종부세",
            "취득세",
            "양도세",
            "재산세",
            "세금",
            "세제",
            "비과세",
            "감면",
            "절세",
            "공시가",
            "공시가격",
            "보유세",
            "상속세",
            "증여세",
        ]
    ):

        return "세제"

    # ----------------------------------------------------------
    # 정책
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "대출",
            "금리",
            "정책",
            "규제",
            "완화",
            "DSR",
            "LTV",
            "DTI",
            "주담대",
            "담보대출",
            "전세대출",
            "임대차",
            "계약갱신",
            "전월세상한",
            "토허제",
            "토지거래허가",
            "실거주의무",
            "거주의무",
        ]
    ):

        return "정책"

    # ----------------------------------------------------------
    # 공급 / 개발
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "신도시",
            "공공주택",
            "공공분양",
            "착공",
            "준공",
            "용적률",
            "복합개발",
            "도시개발",
            "역세권",
            "택지",
            "입주물량",
            "주택공급",
            "공급대책",
            "개발사업",
            "산업단지",
            "도시정비",
        ]
    ):

        return "공급개발"

    # ----------------------------------------------------------
    # 부산 / 경남
    # ----------------------------------------------------------

    if any(
        keyword in t
        for keyword in [
            "부산",
            "해운대",
            "수영구",
            "동래",
            "센텀",
            "광안",
            "명지",
            "에코델타",
            "오시리아",
            "기장",
            "사하",
            "사상",
            "연제",
            "금정",
            "북항",
            "부산진",
            "영도",
            "강서구",
            "창원",
            "김해",
            "양산",
            "밀양",
            "진주",
            "거제",
            "통영",
            "경남",
            "울산",
        ]
    ):

        return "부산경남"

    # ----------------------------------------------------------
    # 시장동향
    # ----------------------------------------------------------

    if is_market_valid(
        title
    ):

        return "시장동향"

    # ----------------------------------------------------------
    # 최종 방어
    # ----------------------------------------------------------

    return "제외"
