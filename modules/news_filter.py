    # ---------------------------------------------------------
    # 5. 제품·가전·소비재 기사 차단
    # ---------------------------------------------------------

    if re.search(
        r"에어컨|실외기|냉방|난방|온수|가전|"
        r"신제품|제품 출시|제품 공개|신기술",
        t,
    ):
        # 주택시장 정책·하자·공급 등과 직접 관련된 경우만 허용
        if not re.search(
            r"주택시장|부동산시장|분양|청약|재건축|재개발|"
            r"정비사업|주택공급|아파트 하자|공동주택 하자",
            t,
        ):
            return False

    # ---------------------------------------------------------
    # 6. 실제 시장 관련 핵심어
    # ---------------------------------------------------------

    if not re.search(
        r"아파트|부동산|주택|전세|월세|임대차|매매|"
        r"집값|전셋값|매매가격|거래량|거래|매물|"
        r"분양|분양가|청약|입주|미분양|"
        r"오피스텔|빌라|다세대|공동주택|"
        r"토지|상가|공시가|실거래|"
        r"재건축|재개발|정비사업|"
        r"건설사|시행사|공사비|PF|HUG|LH|SH|"
        r"주택공급|주거|역세권|용적률|정비구역",
        t,
    ):
        return False

    return True


