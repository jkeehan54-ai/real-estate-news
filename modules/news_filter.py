# 제목 정규화
# ══════════════════════════════════════════════════════════════════════════════

def normalize(title: str) -> str:
    """
    제목 정규화.

    - 매체명 꼬리표 제거
    - [속보] 등의 대괄호 제거
    - 날짜 제거
    - 특수문자 제거
    - 한자 제거
    - 공백 정리
    """

    if not title:
        return ""

    title = str(title).strip()

    # ----------------------------------------------------------
    # 제목 뒤 매체명 제거
    # 예:
    #   기사 제목 - 매일경제
    #   기사 제목 | 한국경제
    # ----------------------------------------------------------

    title = re.split(
        r"\s[-|]\s",
        title,
        maxsplit=1,
    )[0].strip()

    # ----------------------------------------------------------
    # [속보], [단독], [종합] 등 제거
    # ----------------------------------------------------------

    title = re.sub(
        r"^\[[^\]]+\]\s*",
        "",
        title,
    )

    # ----------------------------------------------------------
    # 날짜 제거
    # ----------------------------------------------------------

    title = re.sub(
        r"\d{4}[./-]\d{1,2}[./-]\d{1,2}",
        " ",
        title,
    )

    # ----------------------------------------------------------
    # 특수문자 제거
    # ----------------------------------------------------------

    title = re.sub(
        r"[^\w\s]",
        " ",
        title,
    )

    # ----------------------------------------------------------
    # 단독 한자 제거
    # ----------------------------------------------------------

    title = re.sub(
        r"(?<!\w)[\u4e00-\u9fff](?!\w)",
        " ",
        title,
    )

    # ----------------------------------------------------------
    # 공백 정리
    # ----------------------------------------------------------

    return re.sub(
        r"\s+",
        " ",
        title,
    ).strip()


# ══════════════════════════════════════════════════════════════════════════════
# 키워드 추출
# ══════════════════════════════════════════════════════════════════════════════

def keywords(title: str) -> set:
    """
    정규화된 제목에서 중복 판별용 핵심 키워드를 추출한다.
    """

    normalized = normalize(
        title
    )

    if not normalized:
        return set()

    return {
        word
        for word in normalized.split()
        if word not in STOPWORDS
        and len(word) >= 2
    }


# ══════════════════════════════════════════════════════════════════════════════
# 엔티티 추출
# ══════════════════════════════════════════════════════════════════════════════

def extract_entities(title: str) -> set:
    """
    숫자·단위·지명·기관명을 추출한다.

    중복 기사에서
    동일 지역 / 동일 기관 / 동일 금액 등의
    핵심 엔티티가 겹치는지를 판단하는 데 사용한다.
    """

    if not title:
        return set()

    text = re.sub(
        r"[^\w\s.%]",
        " ",
        str(title),
    )

    entities = set()

    # ----------------------------------------------------------
    # 숫자 + 단위
    # ----------------------------------------------------------

    number_pattern = re.compile(
        r"\d+(?:\.\d+)?\s*"
        r"(?:억|만|건|%|개월|층|평|채|명|가구|조|억원|만원|km|년|세대)"
    )

    for match in number_pattern.finditer(text):

        entities.add(
            match.group().strip()
        )

    # ----------------------------------------------------------
    # 지역
    # ----------------------------------------------------------

    for location in LOC_ENTITIES:

        if location in text:

            entities.add(
                location
            )

    # ----------------------------------------------------------
    # 기관
    # ----------------------------------------------------------

    for organization in ORG_ENTITIES:

        if organization in text:

            entities.add(
                organization
            )

    return entities


# ══════════════════════════════════════════════════════════════════════════════
# 중복 제거
# ══════════════════════════════════════════════════════════════════════════════

def is_duplicate(
    new_title: str,
    seen: list,
) -> bool:
    """
    3단계 중복 판별.

    1단계:
        문자열 유사도

    2단계:
        키워드 Jaccard 유사도

    3단계:
        핵심 엔티티 중복
    """

    if not new_title:
        return False

    if not seen:
        return False

    new_normalized = normalize(
        new_title
    )

    if not new_normalized:
        return False

    new_keywords = keywords(
        new_title
    )

    new_entities = extract_entities(
        new_title
    )

    for old_title in seen:

        if not old_title:
            continue

        old_normalized = normalize(
            old_title
        )

        if not old_normalized:
            continue

        # ------------------------------------------------------
        # 1단계
        # 문자열 유사도
        # ------------------------------------------------------

        similarity = SequenceMatcher(
            None,
            new_normalized,
            old_normalized,
        ).ratio()

        if similarity >= 0.72:

            return True

        # ------------------------------------------------------
        # 2단계
        # 키워드 Jaccard
        # ------------------------------------------------------

        old_keywords = keywords(
            old_title
        )

        union = (
            new_keywords
            | old_keywords
        )

        if union:

            intersection = (
                new_keywords
                & old_keywords
            )

            jaccard = (
                len(intersection)
                / len(union)
            )

            if jaccard >= 0.55:

                return True

        # ------------------------------------------------------
        # 3단계
        # 핵심 엔티티
        # ------------------------------------------------------

        old_entities = extract_entities(
            old_title
        )

        if (
            new_entities
            and old_entities
        ):

            common_entities = (
                new_entities
                & old_entities
            )

            if len(common_entities) >= 2:

                return True

    return False


