def is_estate_related(title: str) -> bool:
    """
    부동산 기사 여부 판단.

    1. 기존 RE_EXCLUDE 적용
    2. 사건·범죄 기사 차단
    3. 금융·산업 기사 차단
    4. 스포츠 기사 차단
    5. 가전·제품 기사 차단
    6. 최종적으로 부동산 핵심어가 있어야 통과
    """

    if not title:
        return False

    t = normalize(title)

    # ---------------------------------------------------------
    # 1. 기존 비부동산 제외어
    # ---------------------------------------------------------

    if RE_EXCLUDE.search(t):
        return False

    # ---------------------------------------------------------
    # 2. 사건·범죄성 기사 차단
    # ---------------------------------------------------------

    if re.search(
        r"살인|살해|흉기|인신매매|폭행|강도|절도|시신|변사|"
        r"체포|구속|검거|입건|범행|범죄",
        t,
    ):
        return False

    # ---------------------------------------------------------
    # 3. 금융·산업 기사 오인 방지
    # ---------------------------------------------------------

    financial_industry = re.search(
        r"SK하이닉스|삼성전자|반도체|배터리|전기차|"
        r"코스피|코스닥|주가|주식|증시|상장|IPO|"
        r"기업대출|기업금융|회사채|자사주|중고차|"
        r"KDB생명|롯데손보|보험|M&A|인수합병|"
        r"자본확충|자본조달",
        t,
    )

    housing_context = re.search(
        r"아파트|주택|부동산|전세|월세|임대|분양|"
        r"청약|재건축|재개발|정비사업|집값|매매|"
        r"실거래|분양가|입주|미분양|주거|토지|"
        r"오피스텔|빌라|공동주택",
        t,
    )

    if financial_industry and not housing_context:
        return False

    # ---------------------------------------------------------
    # 4. 정치·정쟁성 기사 차단
    # ---------------------------------------------------------

    if re.search(
        r"국민의힘|민주당|국힘|여당|야당|정당|정치권|"
        r"국회의원|대통령|총리|장관|시장|시의회|도의회|"
        r"정쟁|비판|공세|무능|논란|사과|선거|투표",
        t,
    ):
        # 실제 주택정책·공급정책 자체를 설명하는 경우만 허용
        if not re.search(
            r"주택공급|공급대책|부동산정책|주택정책|"
            r"부동산규제|대출규제|청약제도|정비사업정책",
            t,
        ):
            return False

    # ---------------------------------------------------------
    # 5. 학교·교육 기사 차단
    # ---------------------------------------------------------

    if re.search(
        r"초등학교|중학교|고등학교|학교|교사|교원|"
        r"교육청|교육부|학생|학부모|수업|개교|"
        r"교육과정",
        t,
    ):
        # 주택 공급이나 부동산 시장과 직접 연결된 경우만 허용
        if not re.search(
            r"아파트|주택|분양|청약|재건축|재개발|"
            r"정비사업|주택공급|입주|부동산",
            t,
        ):
            return False

    # ---------------------------------------------------------
    # 6. 스포츠 기사 오인 방지
    # ---------------------------------------------------------

    if re.search(
        r"손흥민|축구|야구|농구|배구|"
        r"선수|구단|이적|득점|골|경기|"
        r"토트넘|프리미어리그|K리그|월드컵",
        t,
    ):
        return False

    # ---------------------------------------------------------
    # 7. 가전·제품·기술 기사 오인 방지
    # ---------------------------------------------------------

    consumer_tech = re.search(
        r"에어컨|실외기|냉방|난방|가전|"
        r"신제품|신기술|제품 출시|제품 공개",
        t,
    )

    if consumer_tech and not housing_context:
        return False

    # ---------------------------------------------------------
    # 8. 최종 부동산 핵심어 확인
    # ---------------------------------------------------------

    return bool(RE_ESTATE.search(t))
    


